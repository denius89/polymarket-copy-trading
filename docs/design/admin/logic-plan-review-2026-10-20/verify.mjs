import fs from 'node:fs';
import zlib from 'node:zlib';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';

const read = path => fs.readFileSync(new URL(path, import.meta.url));
const checks = JSON.parse(read('./checks.json'));
const packed = read('./native-ru.json.gz');
const raw = zlib.gunzipSync(packed);
const sha = value => crypto.createHash('sha256').update(value).digest('hex');
assert.equal(sha(packed), checks.nativeEvidence.compressedSHA256);
assert.equal(sha(raw), checks.nativeEvidence.uncompressedSHA256);
const evidence = JSON.parse(raw);
const map = JSON.parse(read('../sitemap.json'));
const expected = map.sections.flatMap(section => section.screens.map(screen => screen.id));
const actual = evidence.screens.map(screen => screen.id);
assert.equal(actual.length, 802);
assert.equal(new Set(actual).size, actual.length);
// Preserve the historical 802-screen audit; later registry additions are outside its scope.
assert.ok(actual.every(id => expected.includes(id)));
assert.ok(evidence.screens.every(screen => screen.texts.length && !screen.needsCustomRead));
const known = new Set(map.sections.flatMap(section => section.screens.flatMap(screen => [screen.id, screen.english.id])));
const actions = evidence.screens.flatMap(screen => screen.links.flatMap(link => link.actions));
const navigate = actions.filter(action => action.nav === 'NAVIGATE');
assert.equal(actions.length, checks.mainContentActionRecords);
assert.equal(navigate.length, checks.mainContentNavigateActions);
assert.ok(navigate.every(action => known.has(action.to)));
const visibility = JSON.parse(read('./menu-visibility.json'));
assert.equal(visibility.checks.length, 66);
assert.ok(visibility.checks.every(button => button.visible && !button.hidden.length));
const en = JSON.parse(read('./native-en-sample.json'));
assert.equal(en.screens.length, 3);
for (const screenshot of checks.screenshots) assert.ok(read(`./${screenshot}`).length > 0);
assert.equal(checks.fullManualAcceptance, false);
assert.equal(checks.figmaEdited, false);
console.log(`Evidence verified: ${actual.length} RU main areas, ${navigate.length} registered navigation actions, 3 EN samples; design findings remain open.`);
